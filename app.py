"""
Local PDF RAG Chatbot — Runs completely locally with Ollama, Chroma, and LangChain.

Learning Flow & RAG Architecture:
1. Gradio UI receives a PDF file and a user question.
2. Caching Layer Check:
   - Tier 1: Question-Answer (QA) Cache: If the exact same question was previously asked
     for this PDF, returns the pre-computed answer in <1ms without calling LLM or Chroma.
   - Tier 2: Document / Chunk Cache: If this PDF was already processed, reuses the
     previously chunked documents and Chroma vector store in RAM/disk without re-embedding.
3. Document Processing (on first upload):
   - PyPDFLoader extracts text and metadata page-by-page.
   - RecursiveCharacterTextSplitter divides long pages into overlapping chunks (CHUNK_SIZE, CHUNK_OVERLAP).
4. Vector Embeddings & Storage:
   - OllamaEmbeddings converts text chunks into semantic vector embeddings using nomic-embed-text.
   - Chroma stores the embeddings locally and performs fast vector similarity searches.
5. Hybrid Retrieval:
   - Semantic Similarity Search (Chroma) + Keyword Exact Matching.
   - Deduplication and ranking to ensure the most relevant chunks form the LLM context.
6. Generation:
   - ChatOllama (llama3.2:3b) receives the augmented prompt (PDF context + Question)
     and generates a factual answer strictly grounded in the retrieved chunks.
7. Cache Storage:
   - Stores the generated answer in the QA Cache for immediate reuse if repeated.
"""

import hashlib
from pathlib import Path
import time
import traceback
import gradio as gr

from langchain_community.document_loaders import PyPDFLoader
from langchain_text_splitters import RecursiveCharacterTextSplitter
from langchain_ollama import ChatOllama, OllamaEmbeddings
from langchain_chroma import Chroma
from langchain_core.prompts import ChatPromptTemplate


# ==============================================================================
# CONFIGURATION SETTINGS
# ==============================================================================
# Local model names (must be downloaded with `ollama pull <model>`):
LLM_MODEL = "llama3.2:3b"
EMBEDDING_MODEL = "nomic-embed-text"

# Generation settings:
# Temperature guide:
#   0.0 - 0.2: Highly deterministic and factual (best for RAG / document Q&A)
#   0.5 - 0.7: Balanced creativity and factual accuracy
#   0.8 - 1.0: High creativity and variation
LLM_TEMPERATURE = 0.2
LLM_NUM_PREDICT = 512   # Maximum tokens generated by LLM

# Chunking settings:
CHUNK_SIZE = 900        # Approximate characters per text chunk
CHUNK_OVERLAP = 120     # Overlapping characters between adjacent chunks to preserve context
RETRIEVER_K = 4         # Number of top relevant chunks retrieved by semantic search

# Local folder for Chroma vector database
CHROMA_DIR = Path("chroma_db")
COLLECTION_NAME = "uploaded_pdf"


# ==============================================================================
# CACHING LAYER (Document Cache & QA Cache)
# ==============================================================================
# Why caching is critical in RAG:
#
# 1. Document Cache (Chunk & Vector Store Cache):
#    Extracting text from a PDF and generating vector embeddings via an embedding model
#    is the slowest part of RAG. If a user asks 10 questions about the same PDF, re-parsing
#    and re-embedding the PDF 10 times is extremely wasteful.
#    Solution: Compute the PDF content hash (MD5). If seen before, reuse the in-memory
#    chunks and Chroma vector store immediately!
#
# 2. QA Cache (Exact Question Cache):
#    If the user asks the exact same question (or another user asks the same question),
#    we already have the ground-truth answer and retrieved chunks.
#    Solution: Keyed by (pdf_hash, normalized_question). Returns the answer in <1ms.
#
# 3. Note on Semantic Caching (e.g., GPTCache):
#    If questions have the same meaning with different wording (e.g. "What is habit loop?"
#    vs "Explain the habit loop"), a Semantic Cache embeds the query and checks cosine
#    similarity (> 0.92) to reuse existing answers.
# ==============================================================================

# In-memory document cache: { pdf_hash: {"chunks": [...], "vector_store": Chroma, "filename": str} }
DOCUMENT_CACHE = {}

# In-memory QA cache: { (pdf_hash, normalized_question): {"answer": str, "pages": [...], "timestamp": str} }
QA_CACHE = {}


def compute_file_hash(file_path: str) -> str:
    """Calculates MD5 hash of a file's binary content to uniquely identify documents."""
    hasher = hashlib.md5()
    with open(file_path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            hasher.update(chunk)
    return hasher.hexdigest()


# ==============================================================================
# MODEL INITIALIZATION
# ==============================================================================
def make_llm():
    """Initializes the local Ollama LLM chat model."""
    print(f"[INFO] Initializing ChatOllama with model '{LLM_MODEL}' (temp={LLM_TEMPERATURE})...")
    llm = ChatOllama(
        model=LLM_MODEL,
        temperature=LLM_TEMPERATURE,
        num_predict=LLM_NUM_PREDICT,
    )
    return llm


def make_embeddings():
    """Initializes the local Ollama embeddings model."""
    print(f"[INFO] Initializing OllamaEmbeddings with model '{EMBEDDING_MODEL}'...")
    embeddings = OllamaEmbeddings(model=EMBEDDING_MODEL)
    return embeddings


# ==============================================================================
# PDF LOADING AND SPLITTING
# ==============================================================================
def load_and_split_pdf(pdf_path: str):
    """
    Extracts PDF pages using PyPDFLoader and splits them into overlapping
    chunks using RecursiveCharacterTextSplitter.
    """
    print("\n" + "-" * 50)
    print("[STEP 1 & 2] PDF LOADING AND CHUNKING")
    print("-" * 50)
    print(f"[INPUT] PDF Path: {pdf_path}")

    if not pdf_path:
        raise ValueError("Please upload a PDF file first.")

    pdf_file = Path(pdf_path)
    if not pdf_file.is_file():
        raise FileNotFoundError(f"Uploaded PDF was not found at: {pdf_path}")

    # 1. Extract text from PDF pages
    print("[INFO] Extracting text with PyPDFLoader...")
    pages = PyPDFLoader(str(pdf_file)).load()

    if not pages:
        raise ValueError("No text could be extracted. The PDF may be scanned or empty.")

    print(f"[INFO] Total pages loaded: {len(pages)}")
    print(f"[DEBUG] Page 1 sample (first 250 chars):\n{pages[0].page_content[:250].strip()}...\n")

    # 2. Split pages into overlapping chunks
    print(f"[INFO] Splitting pages (chunk_size={CHUNK_SIZE}, chunk_overlap={CHUNK_OVERLAP})...")
    splitter = RecursiveCharacterTextSplitter(
        chunk_size=CHUNK_SIZE,
        chunk_overlap=CHUNK_OVERLAP,
        length_function=len,
        add_start_index=True,
    )

    chunks = splitter.split_documents(pages)
    print(f"[INFO] Total chunks created: {len(chunks)}")

    # 3. Educational chunk preview (first 3 chunks)
    print("\n[LEARNING PREVIEW: Sample Chunks]")
    sample_count = min(3, len(chunks))
    for i in range(sample_count):
        chunk = chunks[i]
        page_num = chunk.metadata.get("page", 0) + 1
        start_idx = chunk.metadata.get("start_index", 0)
        print(f"  Chunk {i + 1}/{len(chunks)} | Page {page_num} | Start Index {start_idx} | Length: {len(chunk.page_content)} chars")
        print(f"  Content: {chunk.page_content[:150].strip()}...\n")

    if len(chunks) > sample_count:
        print(f"[INFO] ... and {len(chunks) - sample_count} more chunks ready for vector indexing.")

    # Optional keyword check for learning verification
    test_keyword = "Sentence-Based Chunking"
    matches = [i for i, c in enumerate(chunks, 1) if test_keyword.casefold() in c.page_content.casefold()]
    if matches:
        print(f"[DEBUG] Keyword '{test_keyword}' found in chunk index: {matches}")

    return chunks


# ==============================================================================
# VECTOR STORE CREATION (CHROMA)
# ==============================================================================
def build_vector_store(chunks, pdf_hash: str = None):
    """
    Computes vector embeddings for each chunk and indexes them into Chroma DB.
    """
    print("\n" + "-" * 50)
    print("[STEP 3] BUILDING CHROMA VECTOR STORE")
    print("-" * 50)
    print(f"[INFO] Total chunks to embed: {len(chunks)}")

    if not chunks:
        raise ValueError("No chunks available to store in Chroma.")

    embeddings = make_embeddings()

    # Use unique collection per document hash to avoid mixing different documents
    collection_name = f"pdf_{pdf_hash[:12]}" if pdf_hash else COLLECTION_NAME
    CHROMA_DIR.mkdir(parents=True, exist_ok=True)

    print(f"[INFO] Generating embeddings with '{EMBEDDING_MODEL}' into collection '{collection_name}'...")
    start_time = time.time()

    vector_store = Chroma.from_documents(
        documents=chunks,
        embedding=embeddings,
        collection_name=collection_name,
        persist_directory=str(CHROMA_DIR),
    )

    elapsed = time.time() - start_time
    total_stored = vector_store._collection.count()
    print(f"[INFO] Vector store built in {elapsed:.2f}s! Total records indexed: {total_stored}")

    return vector_store


# ==============================================================================
# MAIN RAG PIPELINE: ANSWER QUESTION
# ==============================================================================
def answer_question(pdf_path: str, question: str):
    """
    Main RAG pipeline:
    1. Checks QA Cache for repeat questions (instant return).
    2. Checks Document Cache for already parsed/embedded PDF (avoids re-embedding).
    3. Performs Hybrid Retrieval (Semantic similarity via Chroma + Keyword exact match).
    4. Formulates augmented prompt and queries local LLM (Ollama).
    5. Saves result in QA Cache and returns formatted answer.
    """
    try:
        print("\n" + "=" * 65)
        print(" [NEW USER REQUEST] Local PDF RAG Pipeline")
        print("=" * 65)
        print(f"[INPUT] Question: {question}")
        print(f"[INPUT] PDF Path: {pdf_path}")

        # Basic input validation
        if not pdf_path:
            print("[VALIDATION WARNING] No PDF file uploaded.")
            return "Please upload a PDF file first."

        if not question or not question.strip():
            print("[VALIDATION WARNING] Question string is empty.")
            return "Please enter a question."

        question = question.strip()
        norm_question = question.casefold()

        # Compute document identity hash
        pdf_hash = compute_file_hash(pdf_path)
        pdf_filename = Path(pdf_path).name
        print(f"[INFO] Document: '{pdf_filename}' (MD5: {pdf_hash[:12]}...)")

        # ----------------------------------------------------------------------
        # TIER 1 CACHE: Check Question-Answer (QA) Cache
        # ----------------------------------------------------------------------
        qa_key = (pdf_hash, norm_question)
        if qa_key in QA_CACHE:
            cached = QA_CACHE[qa_key]
            print("\n" + "*" * 60)
            print("⚡ [CACHE HIT - QA CACHE]")
            print(f"  Exact question match found for: '{question}'")
            print("  [LEARNING] Reusing saved answer and source pages immediately.")
            print("  Zero LLM compute needed! 0.0s latency.")
            print("*" * 60 + "\n")

            return (
                f"{cached['answer']}\n\n"
                f"---\n"
                f"Retrieved PDF page(s): {', '.join(cached['pages'])}\n"
                f"*(⚡ Loaded instantly from QA Cache)*"
            )

        print("[CACHE MISS - QA] New question detected. Proceeding to retrieval...")

        # ----------------------------------------------------------------------
        # TIER 2 CACHE: Check Document Chunk & Vector Store Cache
        # ----------------------------------------------------------------------
        if pdf_hash in DOCUMENT_CACHE:
            print("\n" + "*" * 60)
            print("📁 [CACHE HIT - DOCUMENT CACHE]")
            print(f"  PDF '{pdf_filename}' is already in memory!")
            print(f"  [LEARNING] Reusing {len(DOCUMENT_CACHE[pdf_hash]['chunks'])} pre-split chunks & Chroma index.")
            print("  Skipped PDF parsing, text splitting, and embedding generation.")
            print("*" * 60 + "\n")

            cached_doc = DOCUMENT_CACHE[pdf_hash]
            chunks = cached_doc["chunks"]
            vector_store = cached_doc["vector_store"]
        else:
            print("\n📁 [CACHE MISS - DOCUMENT CACHE] First time processing this PDF.")
            print("  [LEARNING] Running full ingestion: parse -> chunk -> embed -> store...")

            # Extract pages & create chunks
            chunks = load_and_split_pdf(pdf_path)

            # Generate embeddings and store in Chroma
            vector_store = build_vector_store(chunks, pdf_hash)

            # Store in Document Cache
            DOCUMENT_CACHE[pdf_hash] = {
                "chunks": chunks,
                "vector_store": vector_store,
                "filename": pdf_filename,
            }
            print(f"[CACHE STORE] Cached {len(chunks)} chunks and vector store for '{pdf_filename}'.")

        # ----------------------------------------------------------------------
        # STEP 4: HYBRID RETRIEVAL (Semantic Search + Keyword Search)
        # ----------------------------------------------------------------------
        print("\n" + "-" * 50)
        print("[STEP 4] HYBRID RETRIEVAL")
        print("-" * 50)
        print(f"[QUERY] '{question}'")

        # 1. Semantic Vector Search via Chroma
        print(f"[RETRIEVAL 1] Querying Chroma vector store (k={RETRIEVER_K})...")
        relevant_docs = vector_store.similarity_search(
            question,
            k=RETRIEVER_K
        )
        print(f"[INFO] Semantic search found: {len(relevant_docs)} chunk(s)")

        for i, doc in enumerate(relevant_docs, start=1):
            page_num = doc.metadata.get("page", 0) + 1
            print(f"  [Semantic Chunk {i}] Page {page_num} | Preview: {doc.page_content[:150].strip()}...")

        # 2. Exact Keyword / Phrase Search across all chunks
        print("\n[RETRIEVAL 2] Scanning for exact phrase/keyword matches...")
        keyword_docs = [
            doc for doc in chunks
            if norm_question in doc.page_content.casefold()
        ]
        print(f"[INFO] Exact phrase matches found: {len(keyword_docs)} chunk(s)")

        # 3. Merge & Deduplicate (prioritizing exact matches, then semantic results)
        retrieved_docs = []
        seen_content = set()

        for doc in keyword_docs + relevant_docs:
            clean_text = doc.page_content.strip()
            if clean_text not in seen_content:
                retrieved_docs.append(doc)
                seen_content.add(clean_text)

            # Limit total context chunks to 6
            if len(retrieved_docs) >= 6:
                break

        print(f"\n[INFO] Final hybrid retrieved chunks (deduplicated): {len(retrieved_docs)}")

        if not retrieved_docs:
            print("[WARNING] No relevant chunks retrieved.")
            return "I couldn't find relevant text in this PDF to answer your question."

        for i, doc in enumerate(retrieved_docs, start=1):
            page_num = doc.metadata.get("page", 0) + 1
            print(f"  [Context Chunk {i}] Page {page_num} | Length: {len(doc.page_content)} chars")

        # ----------------------------------------------------------------------
        # STEP 5: ASSEMBLE CONTEXT & FORMAT PROMPT
        # ----------------------------------------------------------------------
        print("\n" + "-" * 50)
        print("[STEP 5] CONTEXT ASSEMBLY & PROMPT FORMATTING")
        print("-" * 50)

        context = "\n\n".join(
            f"[Page {doc.metadata.get('page', 0) + 1}]\n{doc.page_content}"
            for doc in retrieved_docs
        )
        print(f"[INFO] Total context size: {len(context)} characters")

        prompt = ChatPromptTemplate.from_messages([
            (
                "system",
                "Answer using only the supplied PDF context. "
                "If the answer is not present, say you could not find it. "
                "Do not invent facts."
            ),
            (
                "human",
                "PDF context:\n{context}\n\nQuestion: {question}"
            )
        ])

        messages = prompt.format_messages(
            context=context,
            question=question
        )

        # ----------------------------------------------------------------------
        # STEP 6: INVOKE LOCAL LLM (OLLAMA)
        # ----------------------------------------------------------------------
        print("\n" + "-" * 50)
        print("[STEP 6] LOCAL LLM GENERATION (OLLAMA)")
        print("-" * 50)
        print(f"[INFO] Sending prompt to '{LLM_MODEL}'...")

        start_llm = time.time()
        llm = make_llm()
        response = llm.invoke(messages)
        llm_elapsed = time.time() - start_llm

        print(f"[INFO] LLM generated response in {llm_elapsed:.2f}s")

        pages_used = sorted({
            str(doc.metadata.get("page", 0) + 1)
            for doc in retrieved_docs
        }, key=int)

        print(f"[INFO] Source PDF page(s) referenced: {pages_used}")

        # ----------------------------------------------------------------------
        # STEP 7: SAVE TO QA CACHE
        # ----------------------------------------------------------------------
        QA_CACHE[qa_key] = {
            "answer": response.content,
            "pages": pages_used,
            "timestamp": time.strftime("%Y-%m-%d %H:%M:%S"),
        }
        print(f"[CACHE STORE] Saved response to QA Cache. (Total QA cached items: {len(QA_CACHE)})")
        print("=" * 65)
        print(" [COMPLETED] Answer generated and displayed to user.")
        print("=" * 65 + "\n")

        return (
            f"{response.content}\n\n"
            f"---\n"
            f"Retrieved PDF page(s): {', '.join(pages_used)}\n"
            f"*(Generated locally with Ollama in {llm_elapsed:.1f}s)*"
        )

    except Exception as exc:
        print(f"\n[ERROR] Exception encountered during execution: {type(exc).__name__}: {exc}")
        traceback.print_exc()
        return f"Error: {exc}"


# ==============================================================================
# GRADIO USER INTERFACE
# ==============================================================================
demo = gr.Interface(
    fn=answer_question,
    inputs=[
        gr.File(
            label="Upload PDF",
            file_count="single",
            file_types=[".pdf"],
            type="filepath",  # Passes file path string into answer_question()
        ),
        gr.Textbox(
            label="Ask a question",
            lines=2,
            placeholder="Example: What are the main conclusions?",
        ),
    ],
    outputs=gr.Textbox(label="Answer and retrieved pages", lines=10),
    title="Local PDF RAG Chatbot",
    description=(
        "Runs completely on your computer with Ollama + Chroma DB. "
        "No IBM watsonx.ai API key or paid cloud LLM endpoint is required. "
        "Features multi-level document and question caching for instant repeat queries."
    ),
    flagging_mode="never",
)


if __name__ == "__main__":
    print("\n" + "=" * 60)
    print("Starting Local PDF RAG Chatbot...")
    print(f"LLM: {LLM_MODEL} | Embedding: {EMBEDDING_MODEL}")
    print("Multi-level Caching: Enabled (Document Cache + QA Cache)")
    print("=" * 60 + "\n")

    demo.launch(
        server_name="127.0.0.1",
        server_port=7860,
        share=False
    )
